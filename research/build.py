#!/usr/bin/env python3
"""Build research/INDEX.md and research/THEMES.md from their sources of truth.

Nothing edits INDEX.md or THEMES.md by hand: both are generated, so no agent can
overwrite another's work in them.

- INDEX.md is built from the frontmatter of every note in research/sources/
  (the gist is the first sentence of the note's "## Relevance to the project").
- THEMES.md is built from research/themes/<task-slug>.md, one file per task,
  written only by that task. A theme is a "## <slug>: <Name>" heading, an
  optional description paragraph, then "- " evidence bullets. Several task files
  may add bullets under the same slug; the description comes from the first file
  (alphabetical) that gives one.

Usage:  python3 research/build.py          rebuild both files, print warnings
        python3 research/build.py --check  report only; exit 1 on problems
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SOURCES = ROOT / "sources"
THEMES_DIR = ROOT / "themes"
REQUIRED = ["title", "source_url", "type", "evidence", "filed_by", "relevance"]
HEADER = "<!-- GENERATED by research/build.py. Do not edit: change {what} and run the script. -->\n"


def frontmatter(text):
    m = re.match(r"---\n(.*?)\n---\n", text, re.S)
    if not m:
        return {}
    fm = {}
    for line in m.group(1).splitlines():
        if ":" in line and not line.startswith((" ", "\t", "-")):
            k, v = line.split(":", 1)
            fm[k.strip()] = v.strip().strip('"').strip("'")
    return fm


def gist(text):
    m = re.search(r"## Relevance to the project\s*\n+(.+?)(\n\n|\n#|$)", text, re.S)
    if not m:
        return ""
    para = " ".join(m.group(1).split())
    s = re.split(r"(?<=[.!?])\s", para, maxsplit=1)[0]
    return s if len(s) <= 220 else s[:217].rstrip() + "..."


def build_index(warn):
    rows = {}
    for p in sorted(SOURCES.glob("*.md")):
        if p.name.endswith(".transcript.md"):
            continue
        text = p.read_text()
        fm = frontmatter(text)
        missing = [k for k in REQUIRED if not fm.get(k)]
        if missing:
            warn(f"sources/{p.name}: missing frontmatter {', '.join(missing)}")
        task = fm.get("filed_by") or "unknown"
        line = (f"- [{fm.get('title', p.stem)}](sources/{p.name}) · {fm.get('type', '?')} · "
                f"{fm.get('published', 'unknown')} · relevance {fm.get('relevance', '?')} · "
                f"{gist(text)} · {fm.get('source_url', 'NO SOURCE URL')}")
        rows.setdefault(task, []).append(line)
    out = [HEADER.format(what="the source notes' frontmatter"), "# Research index\n",
           "One line per source note, grouped by the task that filed it. Rules: [README.md](README.md).\n"]
    for task in sorted(rows):
        out.append(f"\n## {task} ({len(rows[task])})\n")
        out.extend(r + "\n" for r in rows[task])
    return "".join(out), sum(len(v) for v in rows.values())


def parse_theme_file(p, warn):
    themes, cur = [], None
    for line in p.read_text().splitlines():
        m = re.match(r"## ([a-z0-9-]+):\s*(.+)$", line)
        if m:
            cur = {"slug": m.group(1), "name": m.group(2).strip(), "desc": [], "bullets": []}
            themes.append(cur)
        elif line.startswith("## "):
            warn(f"themes/{p.name}: heading not in '## slug: Name' form: {line}")
            cur = None
        elif cur is None:
            continue
        elif line.startswith("- "):
            cur["bullets"].append(line)
        elif line.strip() and not cur["bullets"]:
            cur["desc"].append(line.strip())
    return themes


def build_themes(warn):
    merged, order = {}, []
    for p in sorted(THEMES_DIR.glob("*.md")):
        for t in parse_theme_file(p, warn):
            m = merged.get(t["slug"])
            if m is None:
                m = merged[t["slug"]] = {"name": t["name"], "desc": t["desc"], "bullets": []}
                order.append(t["slug"])
            elif not m["desc"] and t["desc"]:
                m["desc"] = t["desc"]
            m["bullets"].extend(t["bullets"])
    out = [HEADER.format(what="research/themes/<your-task>.md"), "# Themes\n\n",
           "The recurring ideas extracted across sources, each with the sources that support it. "
           "Built from research/themes/ (one file per task). Rules: [README.md](README.md).\n"]
    for slug in sorted(order):
        m = merged[slug]
        out.append(f"\n## {slug}: {m['name']}\n")
        if m["desc"]:
            out.append(" ".join(m["desc"]) + "\n")
        out.extend(b + "\n" for b in m["bullets"])
    # Cross-check: themes named in source frontmatter should exist.
    for p in SOURCES.glob("*.md"):
        fm = frontmatter(p.read_text())
        for slug in re.findall(r"[a-z0-9-]+", fm.get("themes", "")):
            if slug not in merged:
                warn(f"sources/{p.name}: theme '{slug}' has no section in research/themes/")
    return "".join(out), len(order), sum(len(m["bullets"]) for m in merged.values())


def main():
    check = "--check" in sys.argv
    problems = []
    index, n_src = build_index(problems.append)
    themes, n_th, n_b = build_themes(problems.append)
    if not check:
        (ROOT / "INDEX.md").write_text(index)
        (ROOT / "THEMES.md").write_text(themes)
    for w in problems:
        print("warning:", w)
    print(f"{n_src} sources indexed; {n_th} themes, {n_b} evidence bullets; {len(problems)} warnings")
    sys.exit(1 if check and problems else 0)


if __name__ == "__main__":
    main()
